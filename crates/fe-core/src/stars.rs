// Space motion (SOFA starpv / pvstar / starpm / pmsafe algorithms).

/// Days per Julian year.
const DJY: f64 = 365.25;
/// Radians to arcseconds.
const DR2AS: f64 = 206_264.806_247_096_36;
/// Speed of light, AU/day.
const DC: f64 = C_KM_DAY / AU_KM;
/// Schwarzschild radius of the Sun, AU (as in `ephem`).
const SRS_AU: f64 = 1.974_125_743_36e-8;

/// Catalogue-style star state: ICRS RA/Dec (rad), dRA/dt and dDec/dt (rad/yr,
/// RA rate *not* multiplied by cos dec), parallax (arcsec), RV (km/s).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Astrometry {
    pub ra: f64,
    pub dec: f64,
    pub pmr: f64,
    pub pmd: f64,
    pub px: f64,
    pub rv: f64,
}

impl StarRecord {
    pub fn astrometry(&self) -> Astrometry {
        let mas = ARCSEC / 1000.0;
        Astrometry {
            ra: self.ra_rad,
            dec: self.dec_rad,
            pmr: self.pmra_mas_yr * mas / self.dec_rad.cos(),
            pmd: self.pmdec_mas_yr * mas,
            px: self.plx_mas / 1000.0,
            rv: self.rv_km_s,
        }
    }
}

type PV = [Vec3; 2];

fn s2pv(theta: f64, phi: f64, r: f64, td: f64, pd: f64, rd: f64) -> PV {
    let (st, ct) = theta.sin_cos();
    let (sp, cp) = phi.sin_cos();
    let rcp = r * cp;
    let (x, y) = (rcp * ct, rcp * st);
    let rpd = r * pd;
    let w = rpd * sp - cp * rd;
    [[x, y, r * sp], [-y * td - w * ct, x * td - w * st, rpd * cp + sp * rd]]
}

fn pv2s(pv: &PV) -> (f64, f64, f64, f64, f64, f64) {
    let [mut x, mut y, mut z] = pv[0];
    let [xd, yd, zd] = pv[1];
    let mut rxy2 = x * x + y * y;
    let mut r2 = rxy2 + z * z;
    let rtrue = r2.sqrt();
    let mut rw = rtrue;
    if rtrue == 0.0 {
        x = xd;
        y = yd;
        z = zd;
        rxy2 = x * x + y * y;
        r2 = rxy2 + z * z;
        rw = r2.sqrt();
    }
    let rxy = rxy2.sqrt();
    let xyp = x * xd + y * yd;
    let (theta, phi, td, pd) = if rxy2 != 0.0 {
        (y.atan2(x), z.atan2(rxy), (x * yd - y * xd) / rxy2, (zd * rxy2 - z * xyp) / (r2 * rxy))
    } else {
        (0.0, if z != 0.0 { z.atan2(rxy) } else { 0.0 }, 0.0, 0.0)
    };
    let rd = if rw != 0.0 { (xyp + z * zd) / rw } else { 0.0 };
    (theta, phi, rtrue, td, pd, rd)
}

/// Catalogue coordinates -> barycentric position (AU) and velocity (AU/day),
/// with the relativistic radial/transverse Doppler correction. Returns the
/// SOFA warning bits (1: parallax floored, 2: speed > 0.5c zeroed, 4: no convergence).
pub fn starpv(a: &Astrometry) -> (PV, i32) {
    const PXMIN: f64 = 1e-7;
    const VMAX: f64 = 0.5;
    const IMAX: usize = 100;
    let mut iwarn = 0;
    let w = if a.px >= PXMIN {
        a.px
    } else {
        iwarn += 1;
        PXMIN
    };
    let r = DR2AS / w;
    let rd = 86400.0 * a.rv * 1e3 / (AU_KM * 1e3);
    let mut pv = s2pv(a.ra, a.dec, r, a.pmr / DJY, a.pmd / DJY, rd);
    if norm(pv[1]) / DC > VMAX {
        pv[1] = [0.0; 3];
        iwarn += 2;
    }
    let x = scale(pv[0], 1.0 / norm(pv[0]));
    let vsr = dot(x, pv[1]);
    let usr = scale(x, vsr);
    let ust = sub(pv[1], usr);
    let vst = norm(ust);
    let (betsr, betst) = (vsr / DC, vst / DC);
    let (mut bett, mut betr) = (betst, betsr);
    let (mut d, mut del) = (0.0, 0.0);
    let (mut od, mut odel, mut odd, mut oddel) = (0.0, 0.0, 0.0, 0.0);
    let mut i = 0;
    while i < IMAX {
        d = 1.0 + betr;
        let w = betr * betr + bett * bett;
        del = -w / ((1.0 - w).sqrt() + 1.0);
        betr = d * betsr + del;
        bett = d * betst;
        if i > 0 {
            let dd = (d - od).abs();
            let ddel = (del - odel).abs();
            if i > 1 && dd >= odd && ddel >= oddel {
                break;
            }
            odd = dd;
            oddel = ddel;
        }
        od = d;
        odel = del;
        i += 1;
    }
    if i >= IMAX {
        iwarn += 4;
    }
    let w = if betsr != 0.0 { d + del / betsr } else { 1.0 };
    pv[1] = add(scale(usr, w), scale(ust, d));
    (pv, iwarn)
}

/// Inverse of `starpv`. `None` for superluminal or null states.
pub fn pvstar(pv: &PV) -> Option<Astrometry> {
    let r = norm(pv[0]);
    let x = scale(pv[0], 1.0 / r);
    let vr = dot(x, pv[1]);
    let ur = scale(x, vr);
    let ut = sub(pv[1], ur);
    let vt = norm(ut);
    let (bett, betr) = (vt / DC, vr / DC);
    let d = 1.0 + betr;
    let w = betr * betr + bett * bett;
    if d == 0.0 || w > 1.0 {
        return None;
    }
    let del = -w / ((1.0 - w).sqrt() + 1.0);
    let ur1 = scale(ur, if betr != 0.0 { (betr - del) / (betr * d) } else { 1.0 });
    let ut1 = scale(ut, 1.0 / d);
    let (a, dec, r, rad, decd, rd) = pv2s(&[pv[0], add(ur1, ut1)]);
    if r == 0.0 {
        return None;
    }
    Some(Astrometry {
        ra: norm_rad(a),
        dec,
        pmr: rad * DJY,
        pmd: decd * DJY,
        px: DR2AS / r,
        rv: 1e-3 * rd * AU_KM * 1e3 / 86400.0,
    })
}

/// Rigorous space motion from TDB `ep1` to `ep2` (JD): barycentric state at
/// `ep2` (AU, AU/day) in the catalogue convention (the position is where the
/// light *received* at `ep2` says the star is, SOFA `starpm`).
pub fn starpm_pv(a: &Astrometry, ep1: f64, ep2: f64) -> (PV, i32) {
    let (pv1, iwarn) = starpv(a);
    (propagate(&pv1, ep1, ep2), iwarn)
}

/// The `starpm` step from a catalogue-epoch state `pv1` (from `starpv`).
pub fn propagate(pv1: &PV, ep1: f64, ep2: f64) -> PV {
    let tl1 = norm(pv1[0]) / DC;
    let dt = ep2 - ep1;
    let p = add(pv1[0], scale(pv1[1], dt + tl1));
    let v = pv1[1];
    let r2 = dot(p, p);
    let rdv = dot(p, v);
    let v2 = dot(v, v);
    let c2mv2 = DC * DC - v2;
    let tl2 = if c2mv2 > 0.0 { (-rdv + (rdv * rdv + c2mv2 * r2).sqrt()) / c2mv2 } else { tl1 };
    [add(pv1[0], scale(v, dt + (tl1 - tl2))), v]
}

/// `starpm` returning catalogue-style coordinates at `ep2`.
pub fn starpm(a: &Astrometry, ep1: f64, ep2: f64) -> Option<Astrometry> {
    pvstar(&starpm_pv(a, ep1, ep2).0)
}

fn s2c(ra: f64, dec: f64) -> Vec3 {
    let (sd, cd) = dec.sin_cos();
    let (sr, cr) = ra.sin_cos();
    [cd * cr, cd * sr, sd]
}

/// `starpm` with SOFA `pmsafe` guards: the parallax is raised to keep the
/// implied transverse speed below ~1 % c, and floored at 5e-7".
pub fn pmsafe_input(a: &Astrometry) -> Astrometry {
    const PXMIN: f64 = 5e-7;
    const F: f64 = 326.0;
    let p0 = s2c(a.ra, a.dec);
    let p1 = s2c(a.ra + a.pmr, a.dec + a.pmd);
    let pm = norm(cross(p0, p1)).atan2(dot(p0, p1)) * F;
    let px = a.px.max(pm).max(PXMIN);
    Astrometry { px, ..*a }
}

/// SOFA `pmsafe`: catalogue coordinates propagated from TDB `ep1` to `ep2`.
pub fn pmsafe(a: &Astrometry, ep1: f64, ep2: f64) -> Option<Astrometry> {
    starpm(&pmsafe_input(a), ep1, ep2)
}

/// Catalogue-epoch barycentric state (AU, AU/day) of a star, `pmsafe` guards applied.
pub fn catalog_pv(rec: &StarRecord) -> [Vec3; 2] {
    starpv(&pmsafe_input(&rec.astrometry())).0
}

/// Barycentric position (AU) of a catalogue star at JD TDB.
pub fn barycentric_au(rec: &StarRecord, jd_tdb: f64) -> Vec3 {
    propagate(&catalog_pv(rec), CATALOG_EPOCH_JD, jd_tdb)[0]
}

