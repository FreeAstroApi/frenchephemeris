"""Optional fixed-star compatibility alias table (private corpus).

The public default catalogue (tools/build_stars.py) uses IAU / SIMBAD /
traditional names and standard designations. Deployments that must return the
names and "Name,nomenclature" strings of classic astrology software can load a
private alias table at runtime (`Engine::with_star_compat`, Python
`Engine(..., star_compat=path)`, env `FRENCHEPHEMERIS_STAR_COMPAT`).

Inputs (private, gitignored, produced by tools/probe_swiss_stars.py and
tools/identify_swiss_stars.py from the licensed oracle's public API):
    private/stars/star_names_swiss.tsv      accepted queries -> returned strings
    private/stars/star_identifications.tsv  returned string -> SIMBAD object / HIP

Commands:
    python tools/build_star_compat.py objects  # tools/star_extra_objects.tsv (public:
                                               # object identifiers only, no names)
    python tools/build_star_compat.py build    # private/stars/star_compat_aliases.tsv
                                               # (needs the built catalog.rs)

Output format (UTF-8 TSV, '#' comments):
    N <folded name key>        <returned string> <record id>   name query
    D <folded designation key> <returned string> <record id>   designation query (",xx")
    C <record id>              <returned string>                string for the record's
                                                                  other (default) keys
Record ids are `StarRecord::id` ("HIP 65474", "SIMBAD M 31", "SYS alf Cen AB", ...).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_stars as B  # noqa: E402

ROOT = B.ROOT
PRIVATE = ROOT / "private" / "stars"
NAMES_TSV = PRIVATE / "star_names_swiss.tsv"
IDENT_TSV = PRIVATE / "star_identifications.tsv"
OUT = PRIVATE / "star_compat_aliases.tsv"

# Classic compact nomenclature (two-letter Greek abbreviation + constellation, numbered
# components with "-n") for IAU-named stars.
GREEK2 = {
    "alf": "al", "bet": "be", "gam": "ga", "del": "de", "eps": "ep", "zet": "ze",
    "eta": "et", "tet": "th", "iot": "io", "kap": "ka", "lam": "la", "mu": "mu",
    "nu": "nu", "ksi": "xi", "omi": "omi", "pi": "pi", "rho": "rh", "sig": "si",
    "tau": "ta", "ups": "up", "phi": "ph", "chi": "ch", "psi": "ps", "ome": "ome",
}


def compact(ident: str, con: str) -> str:
    if not ident or not con:
        return ""
    letters = ident.rstrip("0123456789")
    digits = ident[len(letters):].lstrip("0")
    if letters in GREEK2:
        return f"{GREEK2[letters]}{'-' + digits if digits else ''}{con}"
    if ident.isdigit():
        return f"{int(ident)}{con}"
    return f"{ident}{con}"


# SIMBAD objects that are the same star as a Hipparcos record already in the catalogue
# (SIMBAD keeps the HIP number on a component entry): merged into that record.
SAME_AS_HIP = {
    "* tet01 Eri": 13847,  # 8 mas apart at J1991.25
    # zeta1 Aqr: SIMBAD's place/motion for the component are Gaia DR2 values, which the
    # catalogue must not use; the Hipparcos 2007 solution of the pair (HIP 110960) is.
    "* zet01 Aqr": 110960,
}


def identifications() -> dict[str, object]:
    """Returned string -> record key (as in build_stars: HIP int, SIMBAD main_id, SYS/DEF key)."""
    out = {}
    for r in B.parse_tsv(IDENT_TSV):
        main_id, h = r[1], int(r[2])
        if main_id == "-":
            continue
        out[r[0]] = (B.SYSTEM_OF.get(main_id) or SAME_AS_HIP.get(main_id)
                     or (main_id if main_id in B.DEFINED else (h or main_id)))
    return out


def objects() -> None:
    keys = set(identifications().values())
    rows = sorted((("HIP", str(k)) if isinstance(k, int) else ("SIMBAD", k)) for k in keys
                  if not (isinstance(k, str) and (k in B.SYSTEMS or k in B.DEFINED)))
    lines = ["# Additional catalogue objects beyond the IAU-named stars (HIP numbers and SIMBAD main",
             "# identifiers only). Their names in the catalogue come from public sources; see",
             "# tools/build_stars.py. Generated by tools/build_star_compat.py objects.",
             "# kind\tidentifier"]
    lines += [f"{a}\t{b}" for a, b in rows]
    B.EXTRA_OBJECTS_TSV.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {B.EXTRA_OBJECTS_TSV.relative_to(ROOT)}: {len(rows)} objects")


def catalog_records() -> dict[str, float]:
    """Record id -> V magnitude, from the built catalog.rs."""
    text = B.OUT.read_text(encoding="utf-8")
    return {m.group(1): float(m.group(2)) for m in
            re.finditer(r'StarRecord \{ id: "([^"]*)",.*? vmag: ([-\d.e]+),', text)}


def build() -> None:
    fold = B.fold
    rid = B.record_id
    cat = catalog_records()
    ident = identifications()
    contract = B.parse_tsv(NAMES_TSV)

    names: dict[str, tuple[str, object]] = {}
    desigs: dict[str, tuple[str, object]] = {}
    swiss_of: dict[object, list[str]] = {}
    missing = []
    for row in contract:
        ret, queries = row[0], (row[1].split(";") if len(row) > 1 and row[1] else [])
        k = ident.get(ret)
        if k is None or rid(k) not in cat:
            missing.append(ret)
            continue
        swiss_of.setdefault(k, []).append(ret)
        for q in queries:
            if q.startswith(","):
                desigs.setdefault(fold(q[1:]), (ret, k))
            else:
                names.setdefault(fold(q), (ret, k))

    # Classic string for every record: its own compact designation's string, else its
    # first named string (IAU spelling first, unabbreviated first), else IAU name + compact.
    csn = B.parse_csn(B.CACHE / "IAU-CSN.txt")
    wgsn: dict[int, tuple[str, str]] = {}
    for r in csn:
        wgsn.setdefault(r["hip"], (r["name"], compact(r["id"], r["con"])))
    keys = set(swiss_of) | {h for h in wgsn if rid(h) in cat} | set(B.SYSTEMS)
    canon: dict[object, str] = {}
    for k in keys:
        swiss = swiss_of.get(k, [])
        wname, nom = wgsn.get(k, ("", B.SYSTEMS[k]["nom"] if k in B.SYSTEMS else ""))
        own = desigs.get(fold(nom)) if nom else None
        named = sorted((s for s in swiss if not s.startswith(",")),
                       key=lambda s: (fold(s.split(",")[0]) != fold(wname), "." in s.split(",")[0], s.lower()))
        if own and own[1] == k:
            canon[k] = own[0]
        elif named:
            canon[k] = named[0]
        elif swiss:
            canon[k] = sorted(swiss)[0]
        elif wname:
            canon[k] = f"{wname},{nom}"
    # Compact designations of IAU-named stars (with and without the "-"), brightest first.
    for k in sorted((k for k in wgsn if rid(k) in cat), key=lambda k: cat[rid(k)]):
        nom = wgsn[k][1]
        for d in (nom, nom.replace("-", "")):
            if d and k in canon:
                desigs.setdefault(fold(d), (canon[k], k))

    lines = ["# Fixed-star compatibility alias table (PRIVATE; do not publish).",
             "# Classic-software names and \"Name,nomenclature\" strings, discovered black-box through the",
             "# licensed oracle's public API (tools/probe_swiss_stars.py), mapped to FrenchEphemeris",
             "# catalogue records by independent SIMBAD/Hipparcos identification. Built by",
             "# tools/build_star_compat.py. Format: N|D <folded key> <string> <record id>; C <record id> <string>."]
    lines += [f"N\t{key}\t{s}\t{rid(k)}" for key, (s, k) in sorted(names.items())]
    lines += [f"D\t{key}\t{s}\t{rid(k)}" for key, (s, k) in sorted(desigs.items())]
    lines += [f"C\t{rid(k)}\t{s}" for k, s in sorted(canon.items(), key=lambda x: rid(x[0]))]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(names)} names, {len(desigs)} designations, "
          f"{len(canon)} record strings; returned strings without a catalogue object: {missing}")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "build"
    {"objects": objects, "build": build}[cmd]()
