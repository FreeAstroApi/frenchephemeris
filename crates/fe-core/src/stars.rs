/// One catalogue entry (generated by `tools/build_stars.py`).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct StarRecord {
    /// Stable record identifier: `"HIP 65474"`, `"SIMBAD M 31"`, `"SYS alf Cen AB"`, ...
    pub id: &'static str,
    /// Default display name (IAU WGSN where one exists, else a traditional or SIMBAD
    /// name; empty for objects without a public name).
    pub name: &'static str,
    /// Designation used in the returned string (standard form, e.g. `alf Vir`).
    pub nomenclature: &'static str,
    /// Standard designation, e.g. `alf Vir`, `61 Cyg`, `M 31`.
    pub designation: &'static str,
    pub hip: u32,
    /// ICRS place at the catalogue epoch, radians.
    pub ra_rad: f64,
    pub dec_rad: f64,
    /// Proper motion mu_alpha* = dRA/dt·cos(dec), and mu_delta, mas/yr.
    pub pmra_mas_yr: f64,
    pub pmdec_mas_yr: f64,
    pub plx_mas: f64,
    pub rv_km_s: f64,
    pub vmag: f64,
    /// Bibcode of the radial velocity.
    pub rv_ref: &'static str,
}

/// Every catalogued star.
pub fn catalog() -> &'static [StarRecord] {
    &catalog::STARS
}

/// Every accepted name: (display name, star record).
pub fn names() -> impl Iterator<Item = (&'static str, &'static StarRecord)> {
    catalog::NAMES
        .iter()
        .map(|&(_, full, i)| (full.split(',').next().unwrap_or(""), &catalog::STARS[i as usize]))
}

/// A resolved star: the catalogue record and the full name string it was found under.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Star {
    pub record: &'static StarRecord,
    /// Default returned string `"Name,designation"` (e.g. `"Spica,alf Vir"`); the
    /// name part is empty for objects without a public name (`",109 Vir"`). With a
    /// compatibility table, `lookup_compat` returns that table's string separately.
    pub full: &'static str,
}

impl Star {
    /// The name part of `full` (may be empty).
    pub fn display(&self) -> &'static str {
        self.full.split(',').next().unwrap_or("")
    }

    /// `"Name,designation"`, e.g. `"Spica,alf Vir"` (FreeAstroAPI derives its star
    /// `name` from the part before the comma).
    pub fn full_name(&self) -> String {
        self.full.to_string()
    }

    /// Visual (Johnson V) magnitude; `NO_MAGNITUDE` (999.99) where none is published.
    pub fn magnitude(&self) -> f64 {
        self.record.vmag
    }
}

/// Lookup key: lower case, whitespace removed.
fn fold(s: &str) -> String {
    s.chars().filter(|c| !c.is_whitespace()).flat_map(char::to_lowercase).collect()
}

fn find_idx(t: &'static [(&'static str, &'static str, u16)], key: &str) -> Option<(usize, &'static str)> {
    t.binary_search_by(|(k, ..)| (*k).cmp(key)).ok().map(|i| (t[i].2 as usize, t[i].1))
}

/// Resolve a star name in the default (public) catalogue, case-insensitively and
/// ignoring spaces:
/// - IAU, traditional and SIMBAD names (`"Spica"`, `"asellus australis"`);
/// - `",alf Vir"` (designation after a comma) or `"Spica,anything"` (the name part wins);
/// - bare designations: `"alf Vir"`, `"α Vir"`, `"61 Cyg"`, `"HR 5056"`, `"HD 116658"`,
///   `"HIP 65474"`, `"M 31"`.
///
/// Classic star-number queries (a leading digit, e.g. `"4"`) are not supported.
pub fn lookup(name: &str) -> Result<Star> {
    lookup_compat(name, None).map(|(s, _)| s)
}

/// `lookup` through an optional compatibility alias table: compatibility keys win,
/// and the returned string (second element) comes from the table when it has one
/// for the record. Without a table this is `lookup` with the default string.
pub fn lookup_compat(name: &str, compat: Option<&StarCompat>) -> Result<(Star, String)> {
    let unknown = || Error::InvalidArgument(format!("unknown fixed star {name:?}"));
    let (head, tail) = match name.split_once(',') {
        Some((h, t)) => (fold(h), Some(fold(t))),
        None => (fold(name), None),
    };
    // One key kind (names or designations): compatibility key first, then the default
    // key, whose returned string the table may override for that record.
    let kind = |key: &str, names: bool| -> Option<(usize, String)> {
        let table = if names { &catalog::NAMES[..] } else { &catalog::DESIGNATIONS[..] };
        if let Some(c) = compat {
            let ct = if names { &c.names } else { &c.desigs };
            if let Some((full, i)) = ct.get(key) {
                return Some((*i as usize, full.clone()));
            }
        }
        let (i, full) = find_idx(table, key)?;
        Some((i, compat.and_then(|c| c.canon[i].clone()).unwrap_or_else(|| full.to_string())))
    };
    let via = |key: &str, names_first: bool| -> Option<(Star, String)> {
        let (i, full) = kind(key, names_first).or_else(|| kind(key, !names_first))?;
        Some((Star { record: &catalog::STARS[i], full: record_full(i) }, full))
    };
    if !head.is_empty() {
        return via(&head, true).ok_or_else(unknown);
    }
    match tail {
        Some(t) if !t.is_empty() => via(&t, false).ok_or_else(unknown),
        _ => Err(unknown()),
    }
}

/// The default returned string of record `i`.
fn record_full(i: usize) -> &'static str {
    catalog::FULL[i]
}

/// Optional compatibility alias table (loaded at runtime; not part of the public
/// catalogue): names and `"Name,nomenclature"` strings of classic astrology
/// software, mapped to catalogue records. Format: see tools/build_star_compat.py.
#[derive(Debug, Clone, Default)]
pub struct StarCompat {
    names: std::collections::HashMap<String, (String, u16)>,
    desigs: std::collections::HashMap<String, (String, u16)>,
    /// Returned string per catalogue record index (for the record's default keys).
    canon: Vec<Option<String>>,
}

impl StarCompat {
    /// Parse the TSV table. Records are referenced by `StarRecord::id`; unknown ids
    /// are an error (the table must match the built catalogue).
    pub fn parse(text: &str) -> Result<StarCompat> {
        let index: std::collections::HashMap<&str, u16> =
            catalog::STARS.iter().enumerate().map(|(i, r)| (r.id, i as u16)).collect();
        let bad = |l: &str| Error::InvalidArgument(format!("star compat table: bad line {l:?}"));
        let idx = |id: &str| {
            index
                .get(id)
                .copied()
                .ok_or_else(|| Error::InvalidArgument(format!("star compat table: unknown record {id:?}")))
        };
        let mut c = StarCompat { canon: vec![None; catalog::STARS.len()], ..Default::default() };
        for line in text.lines() {
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let f: Vec<&str> = line.split('\t').collect();
            match f.as_slice() {
                ["N", key, full, id] => {
                    c.names.insert(key.to_string(), (full.to_string(), idx(id)?));
                }
                ["D", key, full, id] => {
                    c.desigs.insert(key.to_string(), (full.to_string(), idx(id)?));
                }
                ["C", id, full] => c.canon[idx(id)? as usize] = Some(full.to_string()),
                _ => return Err(bad(line)),
            }
        }
        Ok(c)
    }

    pub fn load(path: &std::path::Path) -> Result<StarCompat> {
        let text =
            std::fs::read_to_string(path).map_err(|e| Error::Io(format!("{}: {e}", path.display())))?;
        StarCompat::parse(&text)
    }

    /// Number of (name, designation) keys.
    pub fn len(&self) -> (usize, usize) {
        (self.names.len(), self.desigs.len())
    }
}

/// Magnitude reported for objects without a published V magnitude (the
/// classic API's sentinel, e.g. for the Galactic Center).
pub const NO_MAGNITUDE: f64 = 999.99;

/// Classic `fixstar2_mag` / `fixstar_mag` semantics with the default catalogue:
/// (returned string, Johnson V magnitude, or `NO_MAGNITUDE`). Errors for unknown
/// names. `Engine::fixstar_mag` also honours a loaded compatibility table.
pub fn fixstar_mag(name: &str) -> Result<(String, f64)> {
    let s = lookup(name)?;
    Ok((s.full_name(), s.magnitude()))
}

/// `fixstar_mag` for many names.
pub fn fixstars_mag(names: &[&str]) -> Vec<Result<(String, f64)>> {
    names.iter().map(|n| fixstar_mag(n)).collect()
}

