"""Generate crates/fe-core/src/eclipses/saros.rs from NASA's saros series catalogues.

Sources (F. Espenak, NASA GSFC; based on the Five Millennium Canons):
  https://eclipse.gsfc.nasa.gov/SEsaros/SEsaroscat.html   (solar, series 0-187)
  https://eclipse.gsfc.nasa.gov/LEsaros/LEsaroscat.html   (lunar, series 1-180)
Each row gives the series number, its member count and the calendar date of its
first eclipse (Julian calendar before 1582 Oct 15, astronomical year numbering).
Saved (curl) as data/nasa/{SE,LE}saroscat.html; run
  .venv/bin/python -I tools/gen_saros.py data/nasa
"""
import os, re, sys

MON = {m: i + 1 for i, m in enumerate('Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec'.split())}


def jd(y, m, d):
    # Meeus ch. 7, 0h of the date.
    greg = (y, m, d) >= (1582, 10, 15)
    if m <= 2:
        y, m = y - 1, m + 12
    b = 0
    if greg:
        a = y // 100
        b = 2 - a + a // 4
    import math
    return math.floor(365.25 * (y + 4716)) + math.floor(30.6001 * (m + 1)) + d + b - 1524.5


def rows(path):
    txt = re.sub(r'<[^>]*>', '', open(path, encoding='latin-1').read())
    out = []
    for line in txt.splitlines():
        m = re.match(r'\s*(-?\d+)\s+(\d+)\s+[\d.]+\s+(-?\d+) (\w{3}) (\d+)\s', line)
        if m:
            out.append((int(m.group(1)), int(m.group(2)), jd(int(m.group(3)), MON[m.group(4)], int(m.group(5)))))
    return out


def main(nasa):
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', 'crates', 'fe-core', 'src', 'eclipses', 'saros.rs')
    se, le = rows(os.path.join(nasa, 'SEsaroscat.html')), rows(os.path.join(nasa, 'LEsaroscat.html'))
    lines = ['// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-FrenchEphemeris-Commercial',
             '// Copyright (C) 2026 Gabriel Naulleau EI, trading as FreeAstroAPI',
             '// Data: NASA saros catalogues (F. Espenak, NASA/GSFC). See NOTICE.',
             '//! Saros series: first eclipse (JD, 0h of the date) and member count of every',
             '//! series, from NASA\'s saros catalogues (F. Espenak, GSFC; Five Millennium Canons):',
             '//! https://eclipse.gsfc.nasa.gov/SEsaros/SEsaroscat.html and',
             '//! https://eclipse.gsfc.nasa.gov/LEsaros/LEsaroscat.html.',
             '//! Generated by tools/gen_saros.py — do not edit.', '',
             '/// (series, members, JD of the first eclipse\'s date)']
    for name, rs in (('SOLAR', se), ('LUNAR', le)):
        lines.append(f'pub const {name}: [(i32, i32, f64); {len(rs)}] = [')
        lines += [f'    ({s}, {n}, {j:.1f}),' for s, n, j in rs]
        lines.append('];')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(len(se), len(le), out)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'data/nasa')
