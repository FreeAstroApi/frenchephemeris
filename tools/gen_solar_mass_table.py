"""Generate crates/fe-core/src/ephem/solar_mass.rs: the fraction of the solar mass inside a
cylinder of radius b (impact parameter, in solar radii) along the line of sight.

Used for the light deflection of a body seen behind the solar disc: the gravitational
deflection of a ray passing at impact parameter b is proportional to the mass enclosed in
that cylinder divided by b (the Sun treated as transparent), which is continuous at the
limb and falls to zero at the centre.

Source: solar "Model S", J. Christensen-Dalsgaard et al. (1996), Science 272, 1286;
density table cptrho.l5bi.d.15c from https://users-phys.au.dk/jcd/solar_models/

Usage:
    python tools/gen_solar_mass_table.py [path/to/cptrho.l5bi.d.15c]
"""

from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
URL = "https://users-phys.au.dk/jcd/solar_models/cptrho.l5bi.d.15c"
SRC = ROOT / "data" / "sources" / "solar_model" / "cptrho.l5bi.d.15c"
OUT = ROOT / "crates" / "fe-core" / "src" / "ephem" / "solar_mass.rs"
N = 401  # samples of b/R in [0, 1]


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    if not src.exists():
        src.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["curl", "-sSfL", "-o", str(src), URL], check=True)
    sha = hashlib.sha256(src.read_bytes()).hexdigest()
    d = np.loadtxt(src, comments="#")
    r, rho = d[:, 0][::-1], d[:, 2][::-1]
    keep = r <= 1.0
    r, rho = r[keep], rho[keep]
    dm = 4 * np.pi * r**2 * rho
    mass = np.concatenate([[0.0], np.cumsum(0.5 * (dm[1:] + dm[:-1]) * np.diff(r))])
    total = mass[-1]

    def cylinder(b: float) -> float:
        if b <= 0.0:
            return 0.0
        sel = r > b
        rr = r[sel]
        shell = 4 * np.pi * rr**2 * rho[sel] * (1.0 - np.sqrt(1.0 - (b / rr) ** 2))
        return (np.interp(b, r, mass) + np.trapezoid(shell, rr)) / total

    bs = np.linspace(0.0, 1.0, N)
    m = [cylinder(b) for b in bs]
    m[-1] = 1.0
    # Slope dm/d(b/R) for C1 (cubic Hermite) interpolation: smooth positions and speeds.
    # dM_cyl/db = integral over r > b of 4 pi r^2 rho(r) * b / (r sqrt(r^2 - b^2)) dr (analytic in b),
    # evaluated numerically on a fine grid of b instead, which is accurate enough here.
    fine = np.linspace(0.0, 1.0, 20 * (N - 1) + 1)
    mf = np.array([cylinder(b) for b in fine])
    slope = np.gradient(mf, fine)[::20]
    slope[0] = 0.0
    fmt = lambda vals: ",\n".join("    " + ", ".join(f"{v:.9f}" for v in vals[i:i + 6]) for i in range(0, N, 6))
    rows = fmt(m)
    srows = fmt(list(slope))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(f"""// SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-FrenchEphemeris-Commercial
// Copyright (C) 2026 Gabriel Naulleau EI, trading as FreeAstroAPI
// Data: solar Model S (Christensen-Dalsgaard et al. 1996, Science 272, 1286),
// {URL} (sha256 {sha}).
// Generated by tools/gen_solar_mass_table.py -- do not edit.

/// Solar radius used for the impact-parameter scaling, km (as in the eclipse code).
pub const SUN_RADIUS_KM: f64 = crate::eclipses::SUN_RADIUS_KM;

/// Fraction of the solar mass inside a line-of-sight cylinder of radius b,
/// sampled at b/R = i / {N - 1} for i = 0..{N - 1}.
pub const CYLINDER_MASS_FRACTION: [f64; {N}] = [
{rows}
];

/// d(fraction)/d(b/R) at the same samples.
pub const CYLINDER_MASS_SLOPE: [f64; {N}] = [
{srows}
];

/// Cubic Hermite interpolation of the enclosed mass fraction at `b_over_r` (clamped to
/// [0, 1]); continuous first derivative, so positions and speeds stay smooth.
pub fn cylinder_mass_fraction(b_over_r: f64) -> f64 {{
    const STEP: f64 = 1.0 / {N - 1}_f64;
    let x = b_over_r.clamp(0.0, 1.0) / STEP;
    let i = (x.floor() as usize).min({N - 2});
    let t = x - i as f64;
    let (t2, t3) = (t * t, t * t * t);
    let (p0, p1) = (CYLINDER_MASS_FRACTION[i], CYLINDER_MASS_FRACTION[i + 1]);
    let (m0, m1) = (CYLINDER_MASS_SLOPE[i] * STEP, CYLINDER_MASS_SLOPE[i + 1] * STEP);
    (2.0 * t3 - 3.0 * t2 + 1.0) * p0 + (t3 - 2.0 * t2 + t) * m0 + (-2.0 * t3 + 3.0 * t2) * p1 + (t3 - t2) * m1
}}
""")
    peak = max((m[i] / bs[i], bs[i]) for i in range(1, N))
    print(f"wrote {OUT}; peak deflection/limb {peak[0]:.3f} at b/R {peak[1]:.3f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
