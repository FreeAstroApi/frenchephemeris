//! Fixed stars: embedded catalogue, name lookup, rigorous space motion and the
//! same apparent-place chain as the planets.
//!
//! Pipeline for one star at TDB `t` seen from observer O:
//! 1. catalogue ICRS place at J1991.25 (Hipparcos 2007) with proper motion,
//!    parallax and radial velocity -> barycentric position at `t` by
//!    rigorous space motion (SOFA `starpm`/`pmsafe` algorithm, including the
//!    light-time (Roemer) term of the catalogue convention);
//! 2. annual / diurnal parallax: direction from the observer's barycentric
//!    position (Earth, topocenter, Sun or SSB per `CalcOptions::origin`);
//! 3. gravitational deflection by the Sun (SOFA `ldsun`, star at infinity);
//! 4. relativistic annual aberration (SOFA `ab`);
//! 5. GCRS -> requested frame with the epoch's `FrameSet` (`ephem::to_frame`).
//!
//! Distances are |star − observer| in AU (from the parallax), so they follow
//! the usual 6-vector convention; speeds come from the same ±h central
//! differences as `Engine::calc_prepared`.

